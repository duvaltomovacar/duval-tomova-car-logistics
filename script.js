let currentLanguage = localStorage.getItem("dtc-language") || "fr";

if (!translations[currentLanguage]) {
    currentLanguage = "fr";
}
function t(key) {
    return translations[currentLanguage][key] || translations.fr[key] || key;
}

function applyTranslations() {
    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const key = element.dataset.i18n;
        const translation = t(key);

        if (typeof translation === "string") {
            element.textContent = translation;
        }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
        const key = element.dataset.i18nPlaceholder;
        element.placeholder = t(key);
    });

    document.querySelectorAll("[data-status-index]").forEach((element) => {
        const index = Number(element.dataset.statusIndex);
        element.textContent = t("statuses")[index];
    });
}
function translateStatus(status) {
    const index = translations.fr.statuses.indexOf(status);
    return index >= 0 ? t("statuses")[index] : status;
}

function translateDetails(details) {
    const detailsTranslations = {
        "Votre véhicule est en route vers l’Espagne.": {
            es: "Su vehículo está en camino hacia España.",
            de: "Ihr Fahrzeug ist auf dem Weg nach Spanien.",
            en: "Your vehicle is on its way to Spain."
        },
        "Votre véhicule est arrivé en Espagne.": {
            es: "Su vehículo ha llegado a España.",
            de: "Ihr Fahrzeug ist in Spanien angekommen.",
            en: "Your vehicle has arrived in Spain."
        }
    };

    const translation = detailsTranslations[details];

    if (translation && translation[currentLanguage]) {
        return translation[currentLanguage];
    }

    return details;
}

function translatePlace(place) {
    if (!place) return place;

    const places = {
        "Allemagne": {
            es: "Alemania",
            de: "Deutschland",
            en: "Germany"
        },
        "Espagne": {
            es: "España",
            de: "Spanien",
            en: "Spain"
        },
        "Madrid, Espagne": {
            es: "Madrid, España",
            de: "Madrid, Spanien",
            en: "Madrid, Spain"
        }
    };

    return places[place]?.[currentLanguage] || place;
}
let deliveryMap = null;
let deliveryMapMarkers = [];

async function afficherCarteLivraison(delivery) {
    const mapElement = document.getElementById("delivery-map");

    if (!mapElement || !window.L) return;

    const origine = delivery.origin;
    const destination = delivery.destination;

    async function obtenirCoordonnees(lieu) {
        const url = "https://nominatim.openstreetmap.org/search?format=jsonv2&limit=1&q="
            + encodeURIComponent(lieu);

        const response = await fetch(url);
        const results = await response.json();

        if (!results.length) {
            throw new Error("Lieu introuvable : " + lieu);
        }

        return [
            Number(results[0].lat),
            Number(results[0].lon)
        ];
    }

    try {
        const depart = await obtenirCoordonnees(origine);
        const arrivee = await obtenirCoordonnees(destination);

        if (!deliveryMap) {
            deliveryMap = L.map("delivery-map");

            L.tileLayer("https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png", {
                attribution: "&copy; OpenStreetMap"
            }).addTo(deliveryMap);
        }

        deliveryMapMarkers.forEach(marker => deliveryMap.removeLayer(marker));
        deliveryMapMarkers = [];

        const markerDepart = L.marker(depart)
            .addTo(deliveryMap)
            .bindPopup("Départ : " + origine);

        const markerArrivee = L.marker(arrivee)
            .addTo(deliveryMap)
            .bindPopup("Destination : " + destination);

        deliveryMapMarkers.push(markerDepart, markerArrivee);

        const trajet = L.polyline([depart, arrivee], {
            color: "#0b3d91",
            weight: 5
        }).addTo(deliveryMap);

        deliveryMap.fitBounds(trajet.getBounds(), {
            padding: [30, 30]
        });

        setTimeout(() => deliveryMap.invalidateSize(), 200);

    } catch (error) {
        console.error("Erreur de carte :", error);
        mapElement.textContent =
            "Impossible d'afficher la carte pour le moment.";
    }
}
